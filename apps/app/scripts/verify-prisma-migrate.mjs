const emptyRoles = psql(
	emptyDb,
	`select rolname, rolbypassrls from pg_roles
   where rolname in ('device','capture_register','capture_janitor')
   order by 1;`
);
if (
	!emptyRoles.includes("capture_register") ||
	!emptyRoles.includes("device") ||
	!emptyRoles.includes("capture_janitor")
) {
	throw new Error(`empty DB missing roles:\n${emptyRoles}`);
}
const emptyBypass = psql(
	emptyDb,
	`select count(*)::int as n from pg_roles
   where rolname in ('device','capture_register','capture_janitor')
     and (rolbypassrls or rolsuper);`
);
if (!emptyBypass.includes("0")) {
	throw new Error(`empty DB roles must not bypass RLS:\n${emptyBypass}`);
}
